// Builds the UI into crates/fusee/src/http/ui-dist (checked in, so building
// the crate never needs Node) and checks the size budget: 250 KB gzip of
// script and style, 150 KB of fonts.
import { build } from "esbuild";
import { execFileSync } from "node:child_process";
import { copyFileSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { gzipSync } from "node:zlib";

const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, "..", "crates", "fusee", "src", "http", "ui-dist");
const tmp = join(here, ".build");
rmSync(tmp, { recursive: true, force: true });
mkdirSync(join(out, "assets"), { recursive: true });
mkdirSync(tmp, { recursive: true });
const require = createRequire(import.meta.url);

// The theme: the OKLCH generator, run once, written into the stylesheet.
await build({ entryPoints: [join(here, "src/tokens/theme.ts")], bundle: true, format: "esm", outfile: join(tmp, "theme.mjs"), logLevel: "error" });
const { themeStylesheet } = await import(join(tmp, "theme.mjs"));
const css = readFileSync(join(here, "src/styles.css"), "utf8").replace("/* THEME */", themeStylesheet());
writeFileSync(join(tmp, "styles.css"), css);
execFileSync(join(here, "node_modules/.bin/tailwindcss"), ["-c", join(here, "tailwind.config.cjs"), "-i", join(tmp, "styles.css"), "-o", join(out, "assets/app.css"), "--minify"], { stdio: ["ignore", "ignore", "inherit"] });

const app = await build({
  entryPoints: [join(here, "src/main.tsx")],
  bundle: true,
  minify: true,
  format: "esm",
  target: ["es2022"],
  jsx: "automatic",
  outfile: join(out, "assets/app.js"),
  define: { "process.env.NODE_ENV": '"production"' },
  legalComments: "none",
  metafile: true,
  logLevel: "error",
});

copyFileSync(require.resolve("@fontsource-variable/inter/files/inter-latin-wght-normal.woff2"), join(out, "assets/inter.woff2"));
copyFileSync(require.resolve("@fontsource-variable/geist-mono/files/geist-mono-latin-wght-normal.woff2"), join(out, "assets/geist-mono.woff2"));

// The licenses of everything bundled into app.js and of the two fonts, in
// one file served beside them (the bundle itself carries no comments). A
// package without a license file takes the file of a bundled package from
// the same repository; packages with the same text are listed together.
const names = new Set(["@fontsource-variable/inter", "@fontsource-variable/geist-mono"]);
for (const input of Object.keys(app.metafile.inputs)) {
  const m = input.match(/node_modules\/((?:@[^/]+\/)?[^/]+)\//);
  if (m) names.add(m[1]);
}
const packages = [...names].sort().map((name) => {
  const dir = join(here, "node_modules", name);
  const pkg = JSON.parse(readFileSync(join(dir, "package.json"), "utf8"));
  const repo = String(pkg.repository?.url ?? pkg.repository ?? "").replace(/^git\+|\.git$/g, "");
  const file = readdirSync(dir).find((f) => /^(licen[cs]e|copying)(\.(md|txt))?$/i.test(f));
  return { id: `${name}@${pkg.version} (${pkg.license})`, repo, text: file && readFileSync(join(dir, file), "utf8").trim() };
});
const groups = new Map();
for (const p of packages) {
  const text = p.text ?? packages.find((q) => q.text && q.repo === p.repo)?.text
    ?? `The package ships no license file; its license is the one in ${p.repo}.`;
  groups.set(text, [...(groups.get(text) ?? []), p.id]);
}
writeFileSync(
  join(out, "assets/licenses.txt"),
  "Third-party software in Fusee's web UI.\n\n" +
    [...groups].map(([text, ids]) => `${ids.join("\n")}\n\n${text}\n`).join(`\n${"-".repeat(72)}\n\n`),
);

writeFileSync(
  join(out, "index.html"),
  `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta name="color-scheme" content="light dark">
<title>Fusee</title>
<link rel="preload" href="/assets/inter.woff2" as="font" type="font/woff2" crossorigin>
<link rel="stylesheet" href="/assets/app.css">
<script type="module" src="/assets/app.js"></script>
</head>
<body>
<div id="root"></div>
</body>
</html>
`,
);
writeFileSync(
  join(out, "files.rs"),
  `// Generated by ui/build.mjs: the UI's files, embedded. Do not edit.
pub const INDEX: &[u8] = include_bytes!("index.html");
pub const ASSETS: &[(&str, &str, &[u8])] = &[
    ("app.js", "text/javascript; charset=utf-8", include_bytes!("assets/app.js")),
    ("app.css", "text/css; charset=utf-8", include_bytes!("assets/app.css")),
    ("inter.woff2", "font/woff2", include_bytes!("assets/inter.woff2")),
    ("geist-mono.woff2", "font/woff2", include_bytes!("assets/geist-mono.woff2")),
    ("licenses.txt", "text/plain; charset=utf-8", include_bytes!("assets/licenses.txt")),
];
`,
);

const gz = (f) => gzipSync(readFileSync(join(out, "assets", f))).length;
const code = gz("app.js") + gz("app.css");
const fonts = readFileSync(join(out, "assets/inter.woff2")).length + readFileSync(join(out, "assets/geist-mono.woff2")).length;
console.log(`ui: ${(code / 1024).toFixed(1)} KB gzip of script and style (budget 250), ${(fonts / 1024).toFixed(1)} KB of fonts (budget 150)`);
rmSync(tmp, { recursive: true, force: true });
if (code > 250 * 1024 || fonts > 150 * 1024) {
  console.error("ui: over budget");
  process.exit(1);
}
